    public static void ExportModel(UmaContainerCharacter container, string path, PMXExportOptions options)
    {
        options = PMXExportOptions.Resolve(container, options);
        // Some containers hold props or incomplete skeletons rather than a character rig.
        if (!PMXExportOptions.IsHumanoid(container))
        {
            ExportModel((UmaContainer)container, path, options);
            return;
        }
        PMXExportStateSnapshot stateSnapshot = new PMXExportStateSnapshot(container);
        try 
        {
            stateSnapshot.FreezeForExport(nativeFaceProperties: true);
            // PMX 与 VMD 共用同一套 MMD 默认 A-pose，避免导出当前动画帧或近似 T-pose。
            if (options.OrganizeBones) stateSnapshot.ApplyMmdReferencePose();
            else
            {
                container.UmaFaceAnimator?.Rebind();
                container.UmaAnimator?.Rebind();
            }
            container.FaceDrivenKeyTarget?.FacialResetAll();
            AddBlendShape(container, options.OrganizeBones);
            BuildBillboard(container);

            using var materials = new PMXExportMaterials(Path.GetDirectoryName(path));
            var model = ReadPMXModel(container, Array.Empty<string>(), container.CharaEntry, materials, options);

            using (FileStream fileStream = new FileStream(path, FileMode.Create))
            using (BinaryWriter writer = new BinaryWriter(fileStream))
            {
                var config = new ModelConfig() { GlobalToonPath = "Toon" };
                PMXWriter.Write(writer, model, config);
                PMXMmeExporter.Write(path, model);
            }
        }
        finally
        {
            try
            {
                RemoveBillboard(container);
                ClearBlendShape(container);
            }
            finally
            {
                // 临时导出资源清理失败时，也必须恢复角色的姿势和运行时组件。
                stateSnapshot.Dispose();
            }
        }

        UmaViewerUI.Instance.ShowMessage($"PMX Save at {path}", UIMessageType.Success);
    }

