    private static Part[] ReadPartMaterials(List<Renderer> renderers, RawMMDModel model, PMXExportMaterials exportMaterials,
        out List<Material> sourceMaterials, PMXCheekExporter cheek = null, PMXMangaExporter manga = null,
        PMXFaceMaterialExporter faceMaterials = null, PMXMiniExpressionExporter miniExpressions = null)
    {
        List<Part> parts = new List<Part>();
        sourceMaterials = new List<Material>();
        int baseShift = 0;

        foreach (Renderer renderer in renderers)
        {
            Mesh mesh;
            if (renderer is MeshRenderer mr)
            {
                var meshfilter = mr.GetComponent<MeshFilter>();
                mesh = meshfilter.sharedMesh;
            }
            else
            {
                mesh = ((SkinnedMeshRenderer)renderer).sharedMesh;
            }
            var materials = new List<Material>(renderer.sharedMaterials);
            int rendererIndexCount = 0;
            for (int i = 0; i < mesh.subMeshCount; i++)
            {
                var material = (i < materials.Count ? materials[i] : materials[materials.Count - 1]);
                bool isCheek = cheek != null && renderer == cheek.Renderer;
                bool isManga = manga != null && manga.Contains(renderer);
                bool isTear = faceMaterials != null && faceMaterials.IsTear(renderer);
                if (isCheek) material = cheek.Material;
                if (miniExpressions != null) material = miniExpressions.MaterialFor(renderer, i, material);
                var part = new Part();
                part.Material = exportMaterials.Convert(renderer, i, material, model, isCheek, isManga, isTear);
                miniExpressions?.Record(renderer, i, parts.Count, material);
                if (isCheek) cheek.MaterialIndexes.Add(parts.Count);
                if (isManga) manga.RecordMaterial(renderer, parts.Count);
                faceMaterials?.Record(renderer, i, material, parts.Count);
                var subMesh = mesh.GetSubMesh(i);
                // mesh.triangles concatenates submeshes, even when their source
                // index-buffer ranges overlap or are not in ascending order.
                part.BaseShift = baseShift + rendererIndexCount;
                part.TriangleIndexNum = subMesh.indexCount;
                rendererIndexCount += subMesh.indexCount;
                parts.Add(part);
                sourceMaterials.Add(material);
            }
            baseShift += rendererIndexCount;
        }
        return parts.ToArray();
    }

    private static Vertex[] ReadVerticesAndTriangles(List<Renderer> renderers, Dictionary<Transform, int> boneIndexes, ref List<int> triangleList, Transform root)
    {
        return PMXGeometryExporter.Read(renderers, boneIndexes, ref triangleList, root);
    }

    private static int GetBoneIndex(Dictionary<Transform, int> boneIndexes, Transform bone)
    {
        // 被过滤骨的权重转交给最近的有效祖先，保证索引始终指向实际 PMX 骨骼。
        Transform current = bone;
        while (current != null)
        {
            if (boneIndexes.TryGetValue(current, out int index))
            {
                return index;
            }
            current = current.parent;
        }

        // 兜底到「全ての親」。
        return 0;
    }

    /// <summary> Credit to pohype: https://discussions.unity.com/t/reading-meshes-at-runtime-that-are-not-enabled-for-read-write/804189/7 </summary>
    public static Mesh MakeReadableMeshCopy(Mesh source)
    {
        var copy = new Mesh { indexFormat = source.indexFormat };
        try
        {
            copy.SetVertexBufferParams(source.vertexCount, source.GetVertexAttributes());
            for (int stream = 0; stream < source.vertexBufferCount; stream++)
                using (GraphicsBuffer buffer = source.GetVertexBuffer(stream))
                {
                    var bytes = new byte[buffer.stride * buffer.count];
                    buffer.GetData(bytes);
                    copy.SetVertexBufferData(bytes, 0, 0, bytes.Length, stream, MeshUpdateFlags.DontRecalculateBounds);
                }
            using (GraphicsBuffer buffer = source.GetIndexBuffer())
            {
                var bytes = new byte[buffer.stride * buffer.count]; buffer.GetData(bytes);
                copy.SetIndexBufferParams(buffer.count, source.indexFormat);
                copy.SetIndexBufferData(bytes, 0, 0, bytes.Length);
            }
            copy.subMeshCount = source.subMeshCount;
            for (int i = 0; i < source.subMeshCount; i++)
                copy.SetSubMesh(i, source.GetSubMesh(i), MeshUpdateFlags.DontRecalculateBounds);
            copy.bounds = source.bounds;
            if (!source.HasVertexAttribute(VertexAttribute.Normal)) copy.RecalculateNormals();
            return copy;
        }
        catch { UnityEngine.Object.DestroyImmediate(copy); throw; }
    }
