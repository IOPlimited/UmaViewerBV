    public static void ExportModel(UmaContainer container, string path, PMXExportOptions options)
    {

        using var materials = new PMXExportMaterials(Path.GetDirectoryName(path));
        var model = ReadPMXModel(container, Array.Empty<string>(), null, materials, options);

        FileStream fileStream = new FileStream(path, FileMode.Create);
        BinaryWriter writer = new BinaryWriter(fileStream);
        var config = new ModelConfig() { GlobalToonPath = "Toon" };
        PMXWriter.Write(writer, model, config);

        PMXMmeExporter.Write(path, model);
        writer.Close();
        fileStream.Close();

        UmaViewerUI.Instance.ShowMessage($"PMX Save at {path}", UIMessageType.Success);
    }

